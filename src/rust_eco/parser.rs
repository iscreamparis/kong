use std::path::Path;

use anyhow::{Context, Result};
use sha2::{Digest, Sha256};
use tracing::debug;

/// A parsed dependency from Cargo.lock.
#[derive(Debug, Clone)]
pub struct RustDep {
    pub name: String,
    pub version: String,
    /// The Cargo.lock `checksum` (sha256 of the .crate): Cargo's directory
    /// source replacement needs it in each crate's `.cargo-checksum.json`.
    pub checksum: Option<String>,
}

/// Detect and parse Rust dependency files in a project directory.
pub fn detect_and_parse(project_dir: &Path) -> Result<Vec<RustDep>> {
    let cargo_lock = project_dir.join("Cargo.lock");
    if cargo_lock.exists() {
        debug!("Found Cargo.lock");
        return parse_cargo_lock(&cargo_lock);
    }

    Ok(vec![])
}

/// Parse Cargo.lock using the cargo-lock crate.
pub fn parse_cargo_lock(path: &Path) -> Result<Vec<RustDep>> {
    let lockfile = cargo_lock::Lockfile::load(path)
        .with_context(|| format!("failed to parse Cargo.lock: {}", path.display()))?;

    let deps = lockfile
        .packages
        .iter()
        .filter(|pkg| {
            // Skip the root package (source is None for path dependencies)
            pkg.source.is_some()
        })
        .map(|pkg| RustDep {
            name: pkg.name.as_str().to_string(),
            version: pkg.version.to_string(),
            checksum: pkg.checksum.as_ref().map(|c| c.to_string()),
        })
        .collect();

    Ok(deps)
}

/// Names of the lock packages that have no `source`: the workspace root and
/// its path members. Sorted and deduplicated, so the list identifies the
/// project the same way in every worktree (unlike the path-derived slug).
pub fn workspace_members(path: &Path) -> Result<Vec<String>> {
    let lockfile = cargo_lock::Lockfile::load(path)
        .with_context(|| format!("failed to parse Cargo.lock: {}", path.display()))?;
    let mut names: Vec<String> = lockfile
        .packages
        .iter()
        .filter(|pkg| pkg.source.is_none())
        .map(|pkg| pkg.name.as_str().to_string())
        .collect();
    names.sort();
    names.dedup();
    Ok(names)
}

/// sha256 hex of the Cargo.lock bytes with `\r\n` normalised to `\n`, so a
/// Windows checkout with `core.autocrlf=true` hashes like a Linux one.
pub fn lock_hash(path: &Path) -> Result<String> {
    let bytes = std::fs::read(path)
        .with_context(|| format!("failed to read Cargo.lock: {}", path.display()))?;
    let mut normalised = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'\r' && bytes.get(i + 1) == Some(&b'\n') {
            i += 1;
            continue;
        }
        normalised.push(bytes[i]);
        i += 1;
    }
    Ok(hex::encode(Sha256::digest(&normalised)))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SUM_A: &str = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
    const SUM_B: &str = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb";

    fn fixture_lock() -> String {
        format!(
            r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "anyhow",
 "helper",
 "serde",
]

[[package]]
name = "anyhow"
version = "1.0.86"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "{SUM_A}"

[[package]]
name = "helper"
version = "0.2.0"

[[package]]
name = "serde"
version = "1.0.200"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "{SUM_B}"
"#
        )
    }

    #[test]
    fn workspace_members_and_checksums() {
        let dir = tempfile::TempDir::new().unwrap();
        let lock = dir.path().join("Cargo.lock");
        std::fs::write(&lock, fixture_lock()).unwrap();

        assert_eq!(workspace_members(&lock).unwrap(), vec!["app", "helper"]);

        let deps = parse_cargo_lock(&lock).unwrap();
        let sums: Vec<(&str, Option<&str>)> =
            deps.iter().map(|d| (d.name.as_str(), d.checksum.as_deref())).collect();
        assert_eq!(sums, vec![("anyhow", Some(SUM_A)), ("serde", Some(SUM_B))]);
    }

    #[test]
    fn lock_hash_ignores_crlf() {
        let dir = tempfile::TempDir::new().unwrap();
        let lf = dir.path().join("lf.lock");
        let crlf = dir.path().join("crlf.lock");
        let text = fixture_lock();
        std::fs::write(&lf, &text).unwrap();
        std::fs::write(&crlf, text.replace('\n', "\r\n")).unwrap();

        let h = lock_hash(&lf).unwrap();
        assert_eq!(h.len(), 64);
        assert_eq!(h, lock_hash(&crlf).unwrap());
        assert_eq!(h, hex::encode(Sha256::digest(text.as_bytes())));
    }

    #[test]
    fn lock_hash_names_missing_file() {
        let dir = tempfile::TempDir::new().unwrap();
        let err = lock_hash(&dir.path().join("Cargo.lock")).unwrap_err();
        assert!(format!("{err:#}").contains("Cargo.lock"));
    }
}
